#!/usr/bin/env bash
# Publish rendered media to the orphan branch "claude-news-media" so Metricool can fetch it.
# Metricool copies media to its own storage when a post is scheduled, so the branch only
# keeps the last 3 days and is force-pushed as a single commit (no history build-up).
#
# Usage: claude-news/publish_media.sh <out dir containing run folders> <remote url>
set -euo pipefail
OUT="$1"; REMOTE="$2"; BR=claude-news-media
WORK="$(mktemp -d)"
if git ls-remote --exit-code --heads "$REMOTE" "$BR" >/dev/null 2>&1; then
  git clone --quiet --depth 1 --branch "$BR" "$REMOTE" "$WORK/pub"
else
  mkdir -p "$WORK/pub" && git -C "$WORK/pub" init -q && git -C "$WORK/pub" remote add origin "$REMOTE"
fi
cd "$WORK/pub"
CUTOFF=$(TZ=Asia/Kuala_Lumpur date -d '3 days ago' +%F)
for d in */; do
  d="${d%/}"; [[ "$d" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2} ]] || continue
  [[ "${d:0:10}" < "$CUTOFF" ]] && rm -rf "$d" && echo "pruned $d"
done
cp -r "$OUT"/. .
cat > README.md <<'EOF'
Rendered media for @thecyberintellect news posts (last 3 days only). Generated by claude-news/ on main.
EOF
git checkout -q --orphan tmp-media
git add -A
git -c user.name="claude-news-bot" -c user.email="claude-news-bot@users.noreply.github.com" commit -q -m "News media $(TZ=Asia/Kuala_Lumpur date +%F_%H%M)"
git push -q -f origin tmp-media:"$BR"
echo "published to $BR"
